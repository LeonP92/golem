// Codex runs OpenAI's Codex CLI (`codex exec`) headless.
//
// The invocation mirrors the claude-code adapter: one process per role,
// the prompt on stdin. `codex exec -` reads its instructions from stdin
// (verified against codex 0.163.0), which keeps untrusted ticket text out
// of the process list.
//
// Auth is the operator's, resolved by codex itself: a CODEX_API_KEY in the
// environment (exec-only), a saved login in $CODEX_HOME/auth.json, or a
// custom provider in ~/.codex/config.toml ([model_providers.*] with
// base_url/env_key). Custom providers must speak the Responses API — the
// chat-completions wire API was removed from codex in February 2026
// (openai/codex discussion #7782), so a chat-only "OpenAI-compatible"
// server will not work here; that is what the opencode adapter is for.
type Codex struct{ opts Options }

func init() {
	Register("codex", func(o Options) Adapter { return Codex{opts: o} })
}

func (c Codex) Name() string { return "codex" }

// ReservedArgs are the tokens this adapter sets itself. --json is reserved
// because golem parses stdout as the agent's plain-text answer.
func (c Codex) ReservedArgs() []string {
	return []string{"exec", "--sandbox", "-s", "--model", "-m", "--json", "--config", "-c"}
}

// argv builds `codex exec --sandbox <mode> [--model m] [extra] -`.
//
// The mode is workspace-write unless GOLEM_CODEX_SANDBOX says otherwise.
// exec defaults to read-only, which cannot do ticket work, so the flag is
// not optional. The shem container sets danger-full-access: its sandbox
// needs user namespaces Docker does not grant, so workspace-write fails
// every write there, and the container is the boundary. The trailing "-"
// makes codex read the prompt from stdin.
func (c Codex) argv(model string) ([]string, error) {
	cmd := c.opts.Command
	if cmd == "" {
		cmd = "codex"
	}
	sandbox := os.Getenv("GOLEM_CODEX_SANDBOX")
	switch sandbox {
	case "":
		sandbox = "workspace-write"
	case "read-only", "workspace-write", "danger-full-access":
	default:
		return nil, fmt.Errorf("GOLEM_CODEX_SANDBOX=%q is not a codex sandbox mode", sandbox)
	}
	args := []string{cmd, "exec", "--sandbox", sandbox}
	if model != "" {
		if !models.ValidModelID(model) {
			return nil, fmt.Errorf("invalid model id %q", model)
		}
		args = append(args, "--model", model)
	}
	return append(append(args, c.opts.ExtraArgs...), "-"), nil
}

// codexAllowPrefixes are the command prefixes a golem agent may run, as
// codex prefix_rule patterns. This is the claude-code adapter's Bash allow
// list translated to prefix rules: codex patterns are literal token
// prefixes with no glob syntax, so "Bash(git *)" becomes ["git"]. Rules
// govern command execution; file edits stay governed by the workspace-write
// sandbox, which is why claude's Edit(**) entry has no counterpart here.
var codexAllowPrefixes = [][]string{
	{"git"},
	{"golem"}, {"./golem"}, {"./golem.exe"},
	{"go"},
	{"python3"}, {"python"}, {"pip"}, {"pip3"},
	{"npm"}, {"npx"}, {"node"},
	{"cargo"}, {"rustc"}, {"mvn"}, {"gradle"}, {"make"},
	{"ls"}, {"cat"}, {"echo"}, {"mkdir"}, {"cp"}, {"mv"}, {"rm"},
	{"touch"}, {"chmod"}, {"find"}, {"grep"}, {"sed"}, {"awk"},
}

// codexDenyPrefixes are forbidden prefix rules, the same destructive or
// publishing commands the claude adapter denies. Codex applies the
// strictest matching decision (forbidden > prompt > allow), so a deny here
// beats the broader allow prefixes above.
var codexDenyPrefixes = [][]string{
	{"git", "push", "origin", "main"},
	{"git", "push", "--force"},
	{"git", "reset", "--hard"},
	{"git", "rebase"},
	{"npm", "publish"},
	{"cargo", "publish"},
	{"twine", "upload"},
	{"python", "-m", "twine", "upload"},
	{"sudo"},
}

// codexRules renders the allow and deny prefix lists as a Starlark .rules
// file for .codex/rules/. Project rules load only when the project is
// trusted, which PrepareHost arranges; the file is still written when
// untrusted so a later trust decision picks it up unchanged.
func codexRules() string {
	var b strings.Builder
	b.WriteString("# Generated by golem. Mirrors the claude-code adapter's allow/deny list;\n")
	b.WriteString("# regenerate with `golem init --backend codex` rather than editing by hand.\n")
	for _, pattern := range codexDenyPrefixes {
		fmt.Fprintf(&b, "prefix_rule(pattern = [%s], decision = \"forbidden\")\n", quoteTokens(pattern))
	}
	for _, pattern := range codexAllowPrefixes {
		fmt.Fprintf(&b, "prefix_rule(pattern = [%s], decision = \"allow\")\n", quoteTokens(pattern))
	}
	return b.String()
}

func quoteTokens(tokens []string) string {
	quoted := make([]string, len(tokens))
	for i, t := range tokens {
		quoted[i] = fmt.Sprintf("%q", t)
	}
	return strings.Join(quoted, ", ")
}

// writeCodexRules installs golem's rules file under dir's .codex/rules/.
func writeCodexRules(dir string) error {
	rulesDir := filepath.Join(dir, ".codex", "rules")
	if err := os.MkdirAll(rulesDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(rulesDir, "golem.rules"), []byte(codexRules()), 0o644)
}

// GenerateArtifacts writes the codex rules file at the repo root.
//
// There are no per-role files to project: codex has no subagent-definition
// format, so roles reach the agent inlined in the prompt via BuildPrompt,
// exactly as the claude adapter's one-shot invocations already do.
// Writing an AGENTS.md was considered and rejected: it would have to live
// at the repository root, where it collides with the operator's own
// AGENTS.md.
func (c Codex) GenerateArtifacts(repoRoot string, roleContent map[string]string) error {
	return writeCodexRules(repoRoot)
}

// WorktreeSetup installs the same rules in a fresh worktree.
func (c Codex) WorktreeSetup(worktreePath string) error {
	if err := writeCodexRules(worktreePath); err != nil {
		return err
	}
	skipWorktree(worktreePath, ".codex/rules/golem.rules")
	return nil
}

func (c Codex) RunAgent(ctx context.Context, role string, in Context, model string) (Result, error) {
	argv, err := c.argv(model)
	if err != nil {
		return Result{}, err
	}
	cmd := agentCmd(ctx, c.opts, c.opts.RepoRoot, argv...)
	cmd.Stdin = strings.NewReader(BuildPrompt(in))

	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	if err := runAgentCmd(cmd); err != nil {
		// Both streams, as with claude: codex exec streams progress to
		// stderr and prints the final message to stdout, so a failure's
		// reason can be on either.
		return Result{}, fmt.Errorf("codex exec failed for role %s: %w%s%s",
			role, err, labelled("stderr", stderr.String()), labelled("stdout", stdout.String()))
	}
	return Result{Output: stdout.String(), Model: model}, nil
}

func (c Codex) RunPhase(ctx context.Context, dir, prompt string, out io.Writer, model string) error {
	argv, err := c.argv(model)
	if err != nil {
		return err
	}
	cmd := agentCmd(ctx, c.opts, dir, argv...)
	cmd.Stdin = strings.NewReader(prompt)
	cmd.Stdout, cmd.Stderr = out, out
	if err := runAgentCmd(cmd); err != nil {
		return fmt.Errorf("%s: %w", strings.Join(argv, " "), err)
	}
	return nil
}
